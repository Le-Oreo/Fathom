"""FATHOM's dolphin facing forward, drawn pixel by pixel (32x32). Renders a large preview too."""
from PIL import Image

COL = {
    "#": (74, 28, 4), "O": (255, 138, 26), "o": (232, 106, 8), "d": (200, 86, 8), "h": (255, 184, 108),
    "w": (255, 244, 228), "s": (240, 206, 168), "e": (36, 14, 4), "W": (255, 255, 255),
    "p": (255, 128, 108), "m": (110, 40, 6),
}
R = [
    "." * 18 + "##" + "." * 12,
    "." * 17 + "#o#" + "." * 12,
    "." * 16 + "#Oo#" + "." * 12,
    "." * 15 + "#OOo#" + "." * 12,
    "." * 12 + "#" * 9 + "." * 11,
    "." * 10 + "##" + "hhh" + "OOOOO" + "##" + "." * 10,
    "." * 8 + "##" + "hh" + "OOO" + "oo" + "OOOOO" + "##" + "." * 8,
    "." * 7 + "#" + "hh" + "O" * 13 + "o" + "#" + "." * 7,
    "." * 6 + "#" + "h" + "O" * 15 + "oo" + "#" + "." * 6,
    "." * 5 + "#" + "h" + "O" * 17 + "oo" + "#" + "." * 5,
    "." * 5 + "#" + "O" * 18 + "oo" + "#" + "." * 5,
    "." * 4 + "#" + "OOOO" + "ee" + "O" * 10 + "ee" + "OO" + "oo" + "#" + "." * 4,
    "." * 4 + "#" + "OOO" + "eWWe" + "O" * 8 + "eWWe" + "O" + "oo" + "#" + "." * 4,
    "." * 4 + "#" + "OOO" + "eWee" + "O" * 8 + "eWee" + "O" + "oo" + "#" + "." * 4,
    "." * 4 + "#" + "OOO" + "eeee" + "O" * 8 + "eeee" + "O" + "oo" + "#" + "." * 4,
    "." * 4 + "#" + "OOOO" + "ee" + "O" * 10 + "ee" + "OO" + "oo" + "#" + "." * 4,
    "." * 4 + "#" + "O" + "pp" + "OOOOOO" + "hhhh" + "OOOOOO" + "pp" + "o" + "#" + "." * 4,
    "." * 4 + "#" + "O" * 8 + "hwhhhh" + "O" * 7 + "o" + "#" + "." * 4,
    "." * 5 + "#" + "O" * 6 + "m" + "OOOOOO" + "m" + "O" * 5 + "o" + "#" + "." * 5,
    "." * 5 + "#" + "O" * 7 + "m" * 6 + "O" * 6 + "o" + "#" + "." * 5,
    "." * 6 + "#" + "O" * 7 + "hhhh" + "O" * 6 + "o" + "#" + "." * 6,
    "." * 6 + "#" + "O" * 17 + "o" + "#" + "." * 6,
    "." * 6 + "#" + "O" * 17 + "o" + "#" + "." * 6,
    "." * 7 + "#" + "O" * 4 + "w" * 8 + "O" * 3 + "o" + "#" + "." * 7,
    "." * 7 + "#" + "O" * 3 + "w" * 10 + "OO" + "o" + "#" + "." * 7,
    "." * 7 + "#" + "O" * 3 + "w" * 10 + "OO" + "o" + "#" + "." * 7,
    "." * 8 + "#" + "oO" + "w" * 10 + "oo" + "#" + "." * 8,
    "." * 9 + "#" + "o" + "s" * 10 + "o" + "#" + "." * 9,
    "." * 10 + "##" + "o" * 8 + "##" + "." * 10,
    "." * 12 + "#" * 8 + "." * 12,
    "." * 32,
    "." * 32,
]
g = [list(r) for r in R]
assert all(len(r) == 32 for r in R), [i for i, r in enumerate(R) if len(r) != 32]
# flippers, out to the sides and a little down
flip = {(4, 20): "#", (5, 20): "#",
        (2, 21): "#", (3, 21): "#", (4, 21): "O", (5, 21): "O",
        (1, 22): "#", (2, 22): "O", (3, 22): "O", (4, 22): "O", (5, 22): "o",
        (1, 23): "#", (2, 23): "o", (3, 23): "o", (4, 23): "#", (5, 23): "#", (6, 23): "#",
        (2, 24): "#", (3, 24): "#"}
# a second, smaller sparkle low in each eye
g[14][11] = "W"
g[14][23] = "W"
for (x, y), c in flip.items():
    g[y][x] = c
    g[y][31 - x] = "o" if c == "O" else c
img = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
for y in range(32):
    for x in range(32):
        if g[y][x] != ".": img.putpixel((x, y), COL[g[y][x]] + (255,))
img.save("design/dolphin-front.png")
sheet = Image.new("RGBA", (32 * 12 + 240, 32 * 12 + 20), (14, 14, 16, 255))
sheet.alpha_composite(img.resize((384, 384), Image.NEAREST), (10, 10))
y = 10
for s in (1, 2, 4):
    sheet.alpha_composite(img.resize((32 * s, 32 * s), Image.NEAREST), (420, y)); y += 32 * s + 10
sheet.save("design/_front-check.png")
